/**
 * @brief Compute per-reload overhead correction for a given PWM frequency.
 *
 * The old 1500us Sming dispatch estimate does not describe worker reloads.
 * Without on-device worker measurements, default to no compensation rather
 * than subtracting an invented latency. Explicit overrides and calibration
 * tables retain their existing microsecond semantics.
 *
 * Override per channel via setReloadOverheadUs() to calibrate for your
 * specific hardware using the TimingTest_HwPWM sample.
 */
static uint32_t computeReloadOverhead(uint32_t frequency, ledc_timer_bit_t resolution)
{
	if(frequency == 0) {
		return 0;
	}
	// Check hardware-measured calibration table first.
	for(size_t i = 0; i < s_calibCount; ++i) {
		if(s_calibTable[i].frequency == frequency && s_calibTable[i].resolution == resolution) {
			return s_calibTable[i].overheadUs;
		}
	}
	return 0;
}

/**
 * @brief Calculate maximum duty value for given resolution
 */
uint32_t maxDutyForResolution(ledc_timer_bit_t resolution)
{
	return (1U << resolution) - 1;
}

/**
 * @brief Convert frequency to period in microseconds
 */
uint32_t frequencyToPeriod(uint32_t frequency)
{
	return (frequency == 0) ? 0 : (1000000 / frequency);
}

/**
 * @brief Convert period in microseconds to frequency
 */
uint32_t periodToFrequency(uint32_t period_us)
{
	return (period_us == 0) ? 0 : (1000000 / period_us);
}

